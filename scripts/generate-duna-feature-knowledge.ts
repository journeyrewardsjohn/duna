import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { format } from "prettier";

// The manifest is generated on demand and is NOT committed (it is in
// .gitignore): pull requests that add a procedure no longer conflict on it.
// Plain run: write it (only when the content changed). `--check`: verify that
// generation succeeds, is deterministic and well formed, and that nobody
// committed the output again.
async function render(root: string) {
  const surfaceDirectory = join(root, "docs/surfaces");
  const domainRouterDirectory = join(root, "packages/api/src/routers");
  // Domain sub-routers (R3 seams) are mounted from router.ts; read them too so
  // a procedure added in routers/** refreshes the manifest like router.ts does.
  const domainRouterPaths = (
    readdirSync(domainRouterDirectory, { recursive: true }) as string[]
  )
    .map((name) => name.split(sep).join("/"))
    .filter((name) => name.endsWith(".ts") && !name.endsWith(".test.ts"))
    .sort()
    .map((name) => join(domainRouterDirectory, name));
  const sourcePaths = [
    join(root, "docs/BUILD_MATRIX.md"),
    join(root, "packages/api/src/router.ts"),
    ...domainRouterPaths,
    ...readdirSync(surfaceDirectory)
      .filter((name) => name.endsWith(".md") && name !== "README.md")
      .sort()
      .map((name) => join(surfaceDirectory, name)),
  ];

  const sourceFingerprint = createHash("sha256")
    .update(
      sourcePaths
        .map(
          (path) =>
            `${relative(root, path)}\n${readFileSync(path, "utf8").replaceAll("\r\n", "\n")}`,
        )
        .join("\n---\n"),
    )
    .digest("hex");

  const buildMatrix = readFileSync(join(root, "docs/BUILD_MATRIX.md"), "utf8");
  const modules = buildMatrix
    .split("\n")
    .filter((line) => /^\| M\d+\s/.test(line))
    .map((line) =>
      line
        .split("|")
        .slice(1, -1)
        .map((cell) => cell.trim()),
    )
    .filter((cells) => cells.length >= 4)
    .map(([module = "", surfaces = "", _evidence = "", status = ""]) => {
      const match = module.match(/^(M\d+)\s+(.+)$/);
      return {
        id: match?.[1] ?? module,
        name: match?.[2] ?? module,
        surfaces: surfaces
          .split(",")
          .map((surface) => surface.trim())
          .filter(Boolean),
        status: status.replaceAll(/\[([^\]]+)\]\([^\)]+\)/g, "$1"),
      };
    });

  const routerSource = readFileSync(
    join(root, "packages/api/src/router.ts"),
    "utf8",
  );
  const apiCapabilities = [
    ...routerSource.matchAll(
      /^\s{2}([A-Za-z][A-Za-z0-9]*):\s+(?:publicProcedure|protectedProcedure|organizationProcedure|adminProcedure|superAdminProcedure)/gm,
    ),
  ]
    .map((match) => match[1]!)
    .concat(
      // Domain procedures are qualified by their file (for example
      // "conditions.forecast"). The R3 placeholder `status` queries are not
      // product capabilities, so they are left out.
      domainRouterPaths.flatMap((path) =>
        [
          ...readFileSync(path, "utf8").matchAll(
            /^\s{2}([A-Za-z][A-Za-z0-9]*):\s+(?:[A-Za-z]*Procedure)\b/gm,
          ),
        ]
          .map((match) => match[1]!)
          .filter((name) => name !== "status")
          .map(
            (name) =>
              `${relative(domainRouterDirectory, path).replace(/\.ts$/, "").split(sep).join(".")}.${name}`,
          ),
      ),
    )
    .filter((name, index, all) => all.indexOf(name) === index)
    .sort();

  const surfaceGuides = sourcePaths
    .filter((path) => path.startsWith(surfaceDirectory))
    .map((path) => {
      const markdown = readFileSync(path, "utf8");
      const paragraphs = markdown
        .split(/\n\s*\n/)
        .map((paragraph) => paragraph.replaceAll(/\s+/g, " ").trim())
        .filter(
          (paragraph) =>
            paragraph &&
            !paragraph.startsWith("#") &&
            !paragraph.startsWith("|") &&
            !paragraph.startsWith("```") &&
            !paragraph.startsWith("-"),
        );
      return {
        surface: basename(path, ".md"),
        summary: paragraphs[0] ?? "",
        capabilities: [...markdown.matchAll(/^##\s+(.+)$/gm)].map((match) =>
          match[1]!.trim(),
        ),
      };
    });

  const rendered = await format(
    `// This file is generated by scripts/generate-duna-feature-knowledge.ts.\n// Update Duna surface docs, BUILD_MATRIX, or API procedures, then run pnpm knowledge:generate.\n\nexport const generatedDunaFeatureKnowledge = ${JSON.stringify(
      { sourceFingerprint, modules, apiCapabilities, surfaceGuides },
      null,
      2,
    )} as const;\n`,
    { parser: "typescript" },
  );

  return {
    rendered,
    counts: {
      modules: modules.length,
      apiCapabilities: apiCapabilities.length,
      surfaceGuides: surfaceGuides.length,
    },
  };
}

async function main() {
  const root = resolve(import.meta.dirname, "..");
  const outputPath = join(
    root,
    "packages/api/src/generated/duna-feature-knowledge.ts",
  );
  const first = await render(root);

  if (process.argv.includes("--check")) {
    const problems: string[] = [];
    const second = await render(root);
    if (first.rendered !== second.rendered) {
      problems.push("generating twice from the same sources differs");
    }
    for (const [name, count] of Object.entries(first.counts)) {
      if (count === 0) problems.push(`the generated ${name} list is empty`);
    }
    try {
      const tracked = execFileSync(
        "git",
        ["ls-files", "--", relative(root, outputPath)],
        { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
      ).trim();
      if (tracked) {
        problems.push(
          "the generated manifest is committed; it is generated on demand and ignored by git (git rm --cached it)",
        );
      }
    } catch {
      // Not a git checkout (for example a source archive): nothing to check.
    }
    if (problems.length > 0) {
      console.error(
        `Duna AI feature knowledge check failed: ${problems.join("; ")}.`,
      );
      process.exitCode = 1;
    }
    return;
  }

  if (
    !existsSync(outputPath) ||
    readFileSync(outputPath, "utf8") !== first.rendered
  ) {
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, first.rendered);
  }
}

void main();
